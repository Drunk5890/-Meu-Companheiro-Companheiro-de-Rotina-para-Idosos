import java.io.File;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public class BancoDados {
    // O prefixo "file" faz o H2 salvar os dados em arquivo no computador.
    private static final String URL = "jdbc:h2:file:./dados/meucompanheiro";
    private static final String USUARIO = "sa";
    private static final String SENHA = "";

    public static Connection conectar() throws SQLException {
        return DriverManager.getConnection(URL, USUARIO, SENHA);
    }

    public static void iniciar() throws SQLException {
        File pasta = new File("dados");
        if (!pasta.exists() && !pasta.mkdirs()) {
            throw new SQLException("Nao foi possivel criar a pasta dados.");
        }

        // CREATE TABLE IF NOT EXISTS nao apaga cadastros anteriores.
        try (Connection conexao = conectar();
             Statement comando = conexao.createStatement()) {
            comando.executeUpdate(
                "CREATE TABLE IF NOT EXISTS medicamentos (" +
                "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "nome VARCHAR(120) NOT NULL, " +
                "horario VARCHAR(30) NOT NULL, " +
                "tomado BOOLEAN NOT NULL DEFAULT FALSE)"
            );
            comando.executeUpdate(
                "CREATE TABLE IF NOT EXISTS atividades (" +
                "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "nome VARCHAR(120) NOT NULL, " +
                "horario VARCHAR(30) NOT NULL, " +
                "concluida BOOLEAN NOT NULL DEFAULT FALSE)"
            );
        }
    }
}
